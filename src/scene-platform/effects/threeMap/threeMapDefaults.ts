export const createDefaultThreeMapObject = (
  id: string,
  transform: SceneTransform = {
    kind: 'local',
    position: [0, 0, 0],
    rotation: [0, 0, 0],
    scale: [1, 1, 1],
  },
): ThreeMapSceneObject => ({
  id,
  name: '中国3D地图',
  type: 'effect',
  visible: true,
  locked: false,
  order: 0,
  transform,
  effect: createDefaultThreeMapEffect(id),
  metadata: { componentKind: 'three-map', pickable: true },
})
