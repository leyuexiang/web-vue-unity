const goviewIconComponentMap = new Map<string, Component>(
  GOVIEW_ICON_LIST.map((item) => [item.name, item.component]),
)

const goviewIconItemMap = new Map<string, GoviewIconItem>(
  GOVIEW_ICON_LIST.map((item) => [item.name, item]),
)

/**
 * 图标名可能来自静态数据、接口或旧场景。
 * 只允许白名单里的 GoView 图标进入渲染层，避免用户输入任意虚拟模块名造成加载失败。
 */
export const normalizeGoviewIconName = (iconName: unknown) => {
  if (typeof iconName !== 'string') return DEFAULT_GOVIEW_ICON_NAME
  return goviewIconComponentMap.has(iconName) ? iconName : DEFAULT_GOVIEW_ICON_NAME
}

export const resolveGoviewIconComponent = (iconName: unknown) =>
  goviewIconComponentMap.get(normalizeGoviewIconName(iconName)) || IconUimApple

export const resolveGoviewIconItem = (iconName: unknown) =>
  goviewIconItemMap.get(normalizeGoviewIconName(iconName)) || goviewIconItemMap.get(DEFAULT_GOVIEW_ICON_NAME)
